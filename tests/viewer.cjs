const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const {chromium} = require('playwright');

(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(process.env.INSPECTOR_URL||'http://127.0.0.1:19877/',{waitUntil:'networkidle'});
  const inspect=page.locator('#rows button.inspect').first();
  await inspect.waitFor();
  await page.locator('#search').fill('no-matching-request-'+Date.now());
  await page.getByText('No matching requests',{exact:true}).waitFor();
  await page.locator('#clear').click();
  await inspect.waitFor();
  await page.locator('#method').selectOption('GET');
  for(const method of await page.locator('#rows .method').allTextContents())assert.equal(method,'GET');
  await page.locator('#clear').click();
  await page.locator('#pause').click();
  assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'true');
  await page.locator('#pause').click();
  assert.equal(await page.locator('#pause').getAttribute('aria-pressed'),'false');
  if(process.env.SCREENSHOT_DIR){await fs.mkdir(process.env.SCREENSHOT_DIR,{recursive:true});await page.screenshot({path:process.env.SCREENSHOT_DIR+'/desktop.png',fullPage:true});}
  const responsePromise=page.waitForResponse(response=>response.url().includes('/api/events/'));
  await inspect.click();
  const response=await responsePromise;
  const event=await response.json();
  assert.equal(response.status(),200);
  await page.locator('#request-dialog').waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.getElementById('download').disabled);
  assert.equal(await page.locator('.detail-id').textContent(),event.id);
  const box=await page.locator('#request-dialog').boundingBox();
  assert(box && box.y>=0 && box.y<1000 && box.height<=1000,'request details must be visible in the viewport');
  if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/detail.png'});
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#download').click();
  const download=await downloadPromise;
  const saved=JSON.parse(await fs.readFile(await download.path(),'utf8'));
  assert.equal(saved.id,event.id);
  await page.locator('#close-detail').click();
  assert.equal(await page.locator('#request-dialog').evaluate(dialog=>dialog.open),false);
  await page.route('**/api/events/*',route=>route.fulfill({status:404,contentType:'application/json',body:'{"error":"not found"}'}));
  await inspect.click();
  await page.locator('.error-state').getByText('This request is no longer available.').waitFor();
  await page.locator('#close-detail').click();
  await page.unroute('**/api/events/*');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#search').fill('');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'page must fit a mobile viewport');
  if(process.env.SCREENSHOT_DIR)await page.screenshot({path:process.env.SCREENSHOT_DIR+'/mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: search, filters, pause/resume, visible request dialog, download, missing event error and mobile layout');
})().catch(error=>{console.error(error);process.exit(1);});
